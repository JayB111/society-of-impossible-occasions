package se.lexicon.dao;

import se.lexicon.config.DatabaseConnection;
import se.lexicon.exception.DatabaseException;
import se.lexicon.model.Event;

import java.sql.*;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

//Implements the event database operations
public class EventDAOImpl implements EventDAO {
    //Saves a new event to the database
    @Override
    public Event save(Event event) {
        String sql = """
            INSERT INTO events
            (title, description, start_time, end_time, location, capacity)
            VALUES (?, ?, ?, ?, ?, ?)
            """;
        try (Connection connection = DatabaseConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(
                     sql, Statement.RETURN_GENERATED_KEYS)) {
            statement.setString(1, event.getTitle());
            statement.setString(2, event.getDescription());
            statement.setTimestamp(3, Timestamp.valueOf(event.getStartTime()));
            statement.setTimestamp(4, Timestamp.valueOf(event.getEndTime()));
            statement.setString(5, event.getLocation());
            statement.setInt(6, event.getCapacity());
            statement.executeUpdate();
            //Retrieves the ID generated by MySQL
            try (ResultSet keys = statement.getGeneratedKeys()) {
                if (keys.next()) {
                    return new Event(
                            keys.getInt(1),
                            event.getTitle(),
                            event.getDescription(),
                            event.getStartTime(),
                            event.getEndTime(),
                            event.getLocation(),
                            event.getCapacity());
                }
            }
            throw new SQLException("No event ID generated.");
        } catch (SQLException e) {
            throw new DatabaseException("Could not save event.", e);
        }
    }
    //Retrieves an event by ID
    @Override
    public Optional<Event> findById(int id) {
        String sql = "SELECT * FROM events WHERE id = ?";
        try (Connection connection = DatabaseConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setInt(1, id);
            try (ResultSet resultSet = statement.executeQuery()) {
                if (resultSet.next()) {
                    return Optional.of(mapEvent(resultSet));
                }
            }
            return Optional.empty();
        } catch (SQLException e) {
            throw new DatabaseException("Could not find event.", e);
        }
    }
    //Retrieves all events from the database
    @Override
    public List<Event> findAll() {
        List<Event> events = new ArrayList<>();
        String sql = "SELECT * FROM events ORDER BY start_time";
        try (Connection connection = DatabaseConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql);
             ResultSet resultSet = statement.executeQuery()) {
            //Converts each database record into an Event object
            while (resultSet.next()) {
                events.add(mapEvent(resultSet));
            }
            return events;
        } catch (SQLException e) {
            throw new DatabaseException("Could not retrieve events.", e);
        }
    }
    //Retrieves upcoming events in chronological order
    @Override
    public List<Event> findUpcomingEvents() {
        List<Event> events = new ArrayList<>();
        String sql = """
            SELECT * FROM events
            WHERE start_time > CURRENT_TIMESTAMP
            ORDER BY start_time
            """;
        try (Connection connection = DatabaseConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql);
             ResultSet resultSet = statement.executeQuery()) {
            while (resultSet.next()) {
                events.add(mapEvent(resultSet));
            }
            return events;
        } catch (SQLException e) {
            throw new DatabaseException("Could not retrieve upcoming events.", e);
        }
    }
    //Updates an existing event in the database
    @Override
    public boolean update(Event event) {
        String sql = """
            UPDATE events
            SET title = ?, description = ?, start_time = ?,
                end_time = ?, location = ?, capacity = ?
            WHERE id = ?
            """;
        try (Connection connection = DatabaseConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, event.getTitle());
            statement.setString(2, event.getDescription());
            statement.setTimestamp(3, Timestamp.valueOf(event.getStartTime()));
            statement.setTimestamp(4, Timestamp.valueOf(event.getEndTime()));
            statement.setString(5, event.getLocation());
            statement.setInt(6, event.getCapacity());
            statement.setInt(7, event.getId());
            return statement.executeUpdate() > 0;
        } catch (SQLException e) {
            throw new DatabaseException("Could not update event.", e);
        }
    }
    //Deletes an event from the database by ID
    @Override
    public boolean delete(int id) {
        String sql = "DELETE FROM events WHERE id = ?";
        try (Connection connection = DatabaseConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setInt(1, id);
            return statement.executeUpdate() > 0;
        } catch (SQLException e) {
            throw new DatabaseException("Could not delete event.", e);
        }
    }
    //converts a MySQL database record back into a Java Event object.
    private Event mapEvent(ResultSet resultSet) throws SQLException {
        return new Event(
                resultSet.getInt("id"),
                resultSet.getString("title"),
                resultSet.getString("description"),
                resultSet.getTimestamp("start_time").toLocalDateTime(),
                resultSet.getTimestamp("end_time").toLocalDateTime(),
                resultSet.getString("location"),
                resultSet.getInt("capacity"));
    }
}