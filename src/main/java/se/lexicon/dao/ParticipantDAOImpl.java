package se.lexicon.dao;

import se.lexicon.config.DatabaseConnection;
import se.lexicon.exception.DatabaseException;
import se.lexicon.model.Participant;
import se.lexicon.model.IndividualParticipant;
import se.lexicon.model.OrganisationParticipant;

import java.sql.*;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

//Implements agrees to provide the methods defined in the interface
public class ParticipantDAOImpl implements ParticipantDAO {
    //Saves a new participant to the database
    @Override
    public Participant save(Participant participant) {
        String sql = """
            INSERT INTO participants
            (name, email, participant_type, organisation_name)
            VALUES (?, ?, ?, ?)
            """;
        try (Connection connection = DatabaseConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(
                     sql, Statement.RETURN_GENERATED_KEYS)) {
            statement.setString(1, participant.getName());
            statement.setString(2, participant.getEmail());
            statement.setString(3, participant.getParticipantType());
            // Only organisation participants have an organisation name
            if (participant instanceof OrganisationParticipant organisation) {
                statement.setString(4, organisation.getOrganisationName());            } else {
                statement.setNull(4, Types.VARCHAR);
            }
            statement.executeUpdate();
            //Retrieves the ID generated by MySQL
            try (ResultSet keys = statement.getGeneratedKeys()) {
                if (keys.next()) {
                    int id = keys.getInt(1);
                    if (participant instanceof OrganisationParticipant organisation) {
                        return new OrganisationParticipant(
                                id,
                                participant.getName(),
                                participant.getEmail(),
                                organisation.getOrganisationName());
                    }
                    return new IndividualParticipant(
                            id,
                            participant.getName(),
                            participant.getEmail());
                }
            }
            throw new SQLException("No participant ID generated.");
        } catch (SQLException e) {
            throw new DatabaseException("Could not save participant.", e);
        }
    }
    //Retrieves a participant by ID
    @Override
    public Optional<Participant> findById(int id) {
        String sql = "SELECT * FROM participants WHERE id = ?";
        try (Connection connection = DatabaseConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setInt(1, id);
            try (ResultSet resultSet = statement.executeQuery()) {
                if (resultSet.next()) {
                    return Optional.of(mapParticipant(resultSet));
                }
            }
            return Optional.empty();
        } catch (SQLException e) {
            throw new DatabaseException("Could not find participant.", e);
        }
    }
    //Retrieves all participants from the database
    @Override
    public List<Participant> findAll() {
        List<Participant> participants = new ArrayList<>();
        String sql = "SELECT * FROM participants ORDER BY id";
        try (Connection connection = DatabaseConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql);
             ResultSet resultSet = statement.executeQuery()) {
            //Converts each database record into a participant object
            while (resultSet.next()) {
                participants.add(mapParticipant(resultSet));
            }
            return participants;
        } catch (SQLException e) {
            throw new DatabaseException("Could not retrieve participants.", e);
        }
    }
    //Updates an existing participant in the database
    @Override
    public boolean update(Participant participant) {
        String sql = """
            UPDATE participants
            SET name = ?, email = ?, participant_type = ?,
                organisation_name = ?
            WHERE id = ?
            """;
        try (Connection connection = DatabaseConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, participant.getName());
            statement.setString(2, participant.getEmail());
            statement.setString(3, participant.getParticipantType());
            if (participant instanceof OrganisationParticipant organisation) {
                statement.setString(4, organisation.getOrganisationName());
            } else {
                statement.setNull(4, Types.VARCHAR);
            }
            statement.setInt(5, participant.getId());
            //Checks whether a database row was updated
            return statement.executeUpdate() > 0;
        } catch (SQLException e) {
            throw new DatabaseException("Could not update participant.", e);
        }
    }
    //Deletes a participant from the database by ID
    @Override
    public boolean delete(int id) {
        String sql = "DELETE FROM participants WHERE id = ?";
        try (Connection connection = DatabaseConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setInt(1, id);
            //Checks whether a participant was deleted
            return statement.executeUpdate() > 0;
        } catch (SQLException e) {
            throw new DatabaseException("Could not delete participant.", e);
        }
    }
    //Converts a database record into a participant object
    private Participant mapParticipant(ResultSet resultSet) throws SQLException {
        int id = resultSet.getInt("id");
        String name = resultSet.getString("name");
        String email = resultSet.getString("email");
        String type = resultSet.getString("participant_type");
        return switch (type) {
            case "ORGANISATION" -> new OrganisationParticipant(
                    id, name, email,
                    resultSet.getString("organisation_name"));
            case "INDIVIDUAL" -> new IndividualParticipant(
                    id, name, email);
            default -> throw new SQLException("Unknown participant type: " + type);
        };
    }
}